function openImageLightbox(index) {

  const viewport =
    document.getElementById(
      'lightboxTrack'
    );

  if (
    !viewport ||
    !currentGallery.length
  ) {
    return;
  }


  index =
    Math.max(
      0,
      Math.min(
        index,
        currentGallery.length - 1
      )
    );


  viewport.innerHTML =
    currentGallery
      .map(
        (src, j) => `
          <div class="lightbox-slide">
            <img
              src="${src}"
              alt="تصویر ${j + 1}"
            >
          </div>
        `
      )
      .join('');


  openModal(
    'imageLightbox'
  );


  requestAnimationFrame(
    () => {

      const slide =
        viewport.children[index];

      if (!slide) return;

      viewport.scrollTo({
        left: slide.offsetLeft,
        behavior: 'auto'
      });

    }
  );
}


function moveLightbox(dir) {

  const viewport =
    document.getElementById(
      'lightboxTrack'
    );

  if (!viewport) {
    return;
  }

  const step =
    viewport.clientWidth;

  viewport.scrollBy({
    left: dir * step,
    behavior: 'smooth'
  });
}


