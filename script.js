/* =========================
   SCROLL LOCK
========================= */

let lockedScrollY = 0;

function lockPage() {
  if (document.body.classList.contains('modal-lock')) {
    return;
  }

  lockedScrollY =
    window.scrollY ||
    window.pageYOffset ||
    0;

  document.body.classList.add('modal-lock');
  document.body.style.top =
    `-${lockedScrollY}px`;
}


function unlockPage() {
  document.body.classList.remove('modal-lock');
  document.body.style.top = '';

  window.scrollTo({
    top: lockedScrollY,
    left: 0,
    behavior: 'auto'
  });
}


/* =========================
   MODALS
========================= */

function openModal(id) {
  const modal =
    document.getElementById(id);

  if (!modal) return;

  modal.classList.add('open');
  modal.setAttribute(
    'aria-hidden',
    'false'
  );

  if (id !== 'imageLightbox') {
    lockPage();
  }
}


function closeModal(id) {
  const modal =
    document.getElementById(id);

  if (!modal) return;

  modal.classList.remove('open');
  modal.setAttribute(
    'aria-hidden',
    'true'
  );

  if (id === 'imageLightbox') {
    return;
  }

  if (!document.querySelector('.modal.open')) {
    unlockPage();
  }
}


