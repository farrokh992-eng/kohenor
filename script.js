function goToNews(index) {

  if (
    !news.length ||
    !track
  ) {
    return;
  }


  index =
    (index + news.length) %
    news.length;


  const card =
    track.querySelector(
      `.news-card[data-index="${index}"]`
    );


  if (!card) {
    return;
  }


  activeNews = index;


  const target =
    card.offsetLeft -
    (track.clientWidth -
     card.offsetWidth) / 2;


  track.scrollTo({
    left: target,
    behavior: 'smooth'
  });


  setActiveDot(index);
}


