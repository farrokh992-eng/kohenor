function setActiveDot(i) {
  if (!dots) return;

  activeNews = i;

  dots
    .querySelectorAll('button')
    .forEach((b, j) => {
      b.classList.toggle(
        'active',
        j === i
      );
    });
}


function goToNews(i) {
  if (
    !track ||
    !news.length
  ) {
    return;
  }

  i =
    (i + news.length) %
    news.length;

  const card =
    track.querySelector(
      `.news-card[data-index="${i}"]`
    );

  if (!card) return;

  activeNews = i;

  const target =
    card.offsetLeft -
    (
      track.clientWidth -
      card.offsetWidth
    ) / 2;

  track.scrollTo({
    left: target,
    behavior: 'smooth'
  });

  setActiveDot(i);
}


/* =========================
   NEWS TIMER
========================= */

function stopTimer() {
  if (timer !== null) {
    clearInterval(timer);
    timer = null;
  }
}


function startTimer() {
  stopTimer();

  if (news.length <= 1) {
    return;
  }

  timer = setInterval(() => {
    goToNews(activeNews + 1);
  }, 5000);
}


function restartTimer() {
  startTimer();
}


function pauseTimer() {
  stopTimer();
}


