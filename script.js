function restartTimer() {

  if (timer !== null) {
    clearInterval(timer);
  }


  if (news.length <= 1) {
    timer = null;
    return;
  }


  timer =
    setInterval(() => {

      goToNews(
        activeNews + 1
      );

    }, 4000);
}


function pauseTimer() {

  if (timer !== null) {

    clearInterval(timer);

    timer = null;
  }
}


/* =========================================================
   SUPABASE REMOTE CONTENT
========================================================= */

async function loadRemote() {

  if (!sb) {
    return;
  }


  try {

    const cr =
      await sb
        .from('site_content')
        .select('*')
        .in(
          'slug',
          [
            'ashayer',
            'cooperative'
          ]
        );


    if (
      !cr.error &&
      Array.isArray(cr.data)
    ) {

      cr.data.forEach(x => {

        content[x.slug] = x;

      });


      const ashayerExcerpt =
        document.getElementById(
          'ashayerExcerpt'
        );


      const cooperativeExcerpt =
        document.getElementById(
          'cooperativeExcerpt'
        );


      if (ashayerExcerpt) {

        ashayerExcerpt.textContent =
          content.ashayer.excerpt;

      }


      if (cooperativeExcerpt) {

        cooperativeExcerpt.textContent =
          content.cooperative.excerpt;

      }
    }


    const nr =
      await sb
        .from('news')
        .select('*')
        .order(
          'created_at',
          {
            ascending: false
          }
        );


    if (
      !nr.error &&
      nr.data?.length
    ) {

      news =
        nr.data.map(n => ({
          ...n,

          images:
            Array.isArray(n.images)
              ? n.images
              : []
        }));


      renderNews();


      activeNews = 0;


      goToNews(0);


      restartTimer();
    }

  } catch (e) {

    console.warn(
      'Remote content unavailable',
      e
    );

  }
}


