function renderDoc(i = 0) {

  if (!viewer) {
    return;
  }

  const d =
    docs[i];

  if (!d) {
    return;
  }


  viewer.innerHTML = `
    <img
      src="${d.url}"
      alt="${esc(d.title)}"
      loading="lazy"
    >

    <div class="document-caption">
      <strong>
        ${esc(d.title)}
      </strong>

      <br>

      تصویر سند رسمی ارائه‌شده
      در بخش اسناد و مدارک.
    </div>
  `;


  document
    .querySelectorAll(
      '.document-tab'
    )
    .forEach(
      (b, j) => {

        b.classList.toggle(
          'active',
          j === i
        );

      }
    );
}


/*
  Event delegation:
  حتی اگر ساختار اسناد بعداً
  دوباره Render شود، دکمه‌ها
  همچنان قابل استفاده هستند.
*/

let lastDocumentAction = 0;


function selectDocument(button) {

  if (!button) {
    return;
  }

  const now =
    Date.now();

  /*
    جلوگیری از اجرای دوباره
    pointerup + click
  */
  if (
    now - lastDocumentAction < 250
  ) {
    return;
  }

  lastDocumentAction = now;


  const index =
    Number(
      button.dataset.doc
    );


  if (
    Number.isNaN(index) ||
    !docs[index]
  ) {
    return;
  }


  renderDoc(index);
}


