let lockedScrollY = 0;

function lockPage() {

  if (document.body.classList.contains('modal-lock')) {
    return;
  }

  lockedScrollY =
    window.scrollY ||
    window.pageYOffset ||
    0;

  document.body.classList.add('modal-lock');

  document.body.style.top =
    `-${lockedScrollY}px`;
}


function unlockPage() {

  document.body.classList.remove('modal-lock');

  document.body.style.top = '';

  window.scrollTo({
    top: lockedScrollY,
    left: 0,
    behavior: 'auto'
  });
}


