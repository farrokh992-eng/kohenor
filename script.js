let currentGallery = [];

let articleGalleryIndex = 0;

let articleGalleryTimer = null;


/*
   حرکت خودکار تصاویر داخل خبر کامل
   هر ۴ ثانیه
*/

function startArticleGalleryTimer() {

  stopArticleGalleryTimer();

  if (currentGallery.length <= 1) {
    return;
  }

  articleGalleryTimer =
    setInterval(() => {

      articleGalleryIndex =
        (articleGalleryIndex + 1) %
        currentGallery.length;

      scrollArticleGallery(
        articleGalleryIndex
      );

    }, 4000);
}


function stopArticleGalleryTimer() {

  if (articleGalleryTimer !== null) {

    clearInterval(
      articleGalleryTimer
    );

    articleGalleryTimer = null;
  }
}


function scrollArticleGallery(index) {

  const gallery =
    document.querySelector(
      '#articleContent .article-gallery'
    );

  if (!gallery) {
    return;
  }


  const slides =
    gallery.querySelectorAll(
      '.gallery-thumb'
    );

  if (!slides.length) {
    return;
  }


  index =
    (index + slides.length) %
    slides.length;


  articleGalleryIndex = index;


  const slide =
    slides[index];

  if (!slide) {
    return;
  }


  gallery.scrollTo({
    left:
      slide.offsetLeft -
      (gallery.clientWidth -
       slide.offsetWidth) / 2,

    behavior: 'smooth'
  });
}


