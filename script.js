function restartTimer() {

  clearInterval(timer);

  timer = null;


  if (news.length <= 1) {
    return;
  }


  timer = setInterval(() => {

    goToNews(
      activeNews + 1
    );

  }, 4000);
}


function pauseTimer() {

  clearInterval(timer);

  timer = null;
}


