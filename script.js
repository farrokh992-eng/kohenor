function openModal(id) {

  const m =
    document.getElementById(id);

  if (!m) return;

  m.classList.add('open');

  m.setAttribute(
    'aria-hidden',
    'false'
  );

  if (id !== 'imageLightbox') {
    lockPage();
  }
}


function closeModal(id) {

  const m =
    document.getElementById(id);

  if (!m) return;

  m.classList.remove('open');

  m.setAttribute(
    'aria-hidden',
    'true'
  );


  if (id === 'imageLightbox') {

    stopLightboxTimer();

    return;
  }


  if (!document.querySelector('.modal.open')) {
    unlockPage();
  }
}


